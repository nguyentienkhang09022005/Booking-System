-- =============================================
-- PERSONAL NOTEBOOK - SỔ TAY CÁ NHÂN
-- =============================================

-- Bảng Notebook (Đại diện 1 cuốn sổ tay theo trip/event)
CREATE TABLE IF NOT EXISTS NOTEBOOK
(
    ID_NOTEBOOK UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ID_USER UUID NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    DESCRIPTION TEXT,
    COVER_IMAGE VARCHAR(500),
    TEMPLATE VARCHAR(50) DEFAULT 'CUSTOM' CHECK (TEMPLATE IN ('CUSTOM', 'TRIP_PLANNER', 'PACKING_LIST', 'EXPENSE')),
    IS_FAVORITE BOOLEAN DEFAULT FALSE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_NOTEBOOK_USER FOREIGN KEY (ID_USER) REFERENCES USERS(ID_USER) ON DELETE CASCADE
);

-- Bảng Note (Các trang/bài viết trong sổ tay)
CREATE TABLE IF NOT EXISTS NOTE
(
    ID_NOTE UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ID_NOTEBOOK UUID NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    DISPLAY_ORDER INT DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_NOTE_NOTEBOOK FOREIGN KEY (ID_NOTEBOOK) REFERENCES NOTEBOOK(ID_NOTEBOOK) ON DELETE CASCADE
);

-- Bảng NoteBlock (Khối nội dung trong mỗi note)
CREATE TABLE IF NOT EXISTS NOTE_BLOCK
(
    ID_BLOCK UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ID_NOTE UUID NOT NULL,
    BLOCK_TYPE VARCHAR(20) NOT NULL CHECK (BLOCK_TYPE IN ('TEXT', 'IMAGE', 'HEADING', 'LIST', 'CHECKLIST', 'QUOTE', 'LINK', 'TABLE')),
    CONTENT TEXT,
    METADATA JSONB,
    DISPLAY_ORDER INT DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_NOTE_BLOCK_NOTE FOREIGN KEY (ID_NOTE) REFERENCES NOTE(ID_NOTE) ON DELETE CASCADE
);

-- Indexes cho tìm kiếm và sắp xếp
CREATE INDEX IF NOT EXISTS IDX_NOTEBOOK_USER ON NOTEBOOK(ID_USER);
CREATE INDEX IF NOT EXISTS IDX_NOTE_NOTEBOOK ON NOTE(ID_NOTEBOOK);
CREATE INDEX IF NOT EXISTS IDX_NOTE_BLOCK_NOTE ON NOTE_BLOCK(ID_NOTE);
CREATE INDEX IF NOT EXISTS IDX_NOTE_BLOCK_ORDER ON NOTE_BLOCK(ID_NOTE, DISPLAY_ORDER);