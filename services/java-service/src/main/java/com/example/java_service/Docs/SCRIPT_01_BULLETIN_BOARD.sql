-- Bulletin Board - Bảng Tin Thông Báo
-- Database: PostgreSQL

-- Bảng bản tin thông báo
CREATE TABLE IF NOT EXISTS BULLETIN_BOARD
(
    ID_BULLETIN UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ID_USER UUID NOT NULL,
    TITLE VARCHAR(200) NOT NULL,
    CONTENT TEXT,
    TARGET_AUDIENCE VARCHAR(20) DEFAULT 'CUSTOMER' CHECK (TARGET_AUDIENCE IN ('ALL', 'CUSTOMER', 'BUSINESS')),
    STATUS VARCHAR(20) DEFAULT 'PENDING' CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED', 'EXPIRED')),
    PRIORITY INT DEFAULT 0,
    IS_APPROVED BOOLEAN DEFAULT FALSE,
    START_DATE TIMESTAMP,
    END_DATE TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    APPROVED_AT TIMESTAMP,
    CONSTRAINT FK_BULLETIN_USER FOREIGN KEY (ID_USER) REFERENCES USERS(ID_USER) ON DELETE CASCADE
);

-- Index cho tìm kiếm nhanh
CREATE INDEX IF NOT EXISTS BULLETIN_BOARD_STATUS_IDX ON BULLETIN_BOARD(STATUS);
CREATE INDEX IF NOT EXISTS BULLETIN_BOARD_TARGET_AUDIENCE_IDX ON BULLETIN_BOARD(TARGET_AUDIENCE);
CREATE INDEX IF NOT EXISTS BULLETIN_BOARD_CREATED_AT_IDX ON BULLETIN_BOARD(CREATED_AT DESC);

-- Ghi chú:
-- - TARGET_AUDIENCE: 'CUSTOMER' là mặc định khi Business tạo, 'ALL'/'BUSINESS' chỉ Admin được tạo
-- - STATUS: 'PENDING' cho Business tạo (chờ duyệt), 'APPROVED'/'REJECTED'/'EXPIRED' là trạng thái
-- - IS_APPROVED: TRUE = đã duyệt (Admin tạo sẽ tự động TRUE)
-- - Images: Dùng chung MongoDB collection `images` với refId → ID_BULLETIN, type = 'bulletin'